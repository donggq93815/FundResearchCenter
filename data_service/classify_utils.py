def classify_name(name):
    """基于基金名称关键词，推断 (company, industry, themes)。"""
    if not name:
        return None, None, []
    industry = None
    for ind_id, kws in INDUSTRY_KEYWORDS.items():
        if any(kw in name for kw in kws):
            industry = ind_id
            break
    themes = [theme for theme, kws in THEME_KEYWORDS.items() if any(kw in name for kw in kws)]
    company = None
    for comp in COMPANY_PREFIXES:
        if name.startswith(comp):
            company = comp
            break
    return company, industry, themes


def classify_type(name):
    """
    基于基金名称关键词推断基金类型（东财 rankhandler ft=all 时字段[17]不表达类型）。
    返回与前端策略分组子类对齐的类型名：
      股票型 / 混合型 / 债券型 / 指数型 / 货币型 / QDII / FOF / REITs / 商品型 / 其他
    """
    if not name:
        return "其他"
    n = name.upper()
    # 优先级：特殊类型先判
    if "REIT" in n:
        return "REITs"
    if "FOF" in n:
        return "FOF"
    if "QDII" in n:
        return "QDII"
    if "货币" in name or "现金" in name or "理财" in name or "添利" in name or "活期" in name:
        return "货币型"
    if "商品" in name or "黄金" in name or "白银" in name or "原油" in name or "豆粕" in name:
        return "商品型"
    if "指数" in name or "ETF" in n or "联接" in name or "增强" in name:
        return "指数型"
    if "债券" in name or "债" in name or "纯债" in name or "短债" in name:
        return "债券型"
    if "混合" in name:
        return "混合型"
    if "股票" in name:
        return "股票型"
    return "其他"
